-- ============================================================================
-- V53 菜单改名：「资债权证」→「资债权证记录」
--
-- 侧栏分组名由 menu 表的 name 决定（前端 MenuProvider 直接取 DB 树渲染 title，
-- 静态 MENU 仅作接口失败时的兜底），因此只改前端代码无法让已存在的库生效，
-- 必须用迁移改库；`frontend/admin-web/src/pages/modules.tsx` 的静态兜底同步改名。
--
-- 只改 deed 这个目录自身的显示名，不动其子菜单
-- （权证信息 / 抵押列表 / 资产调拨 / 评估申请），也不动任何 code / path / 权限行。
-- menu 表无 updated_at 列，故只更新 name；两条 UPDATE 均幂等，可重复执行。
-- ============================================================================

-- 主路径：按 code 精确定位目录行
UPDATE menu
SET name = '资债权证记录'
WHERE code = 'deed'
  AND menu_type = 'dir';

-- 兜底：若该目录行的 code 在运行期被改过（菜单管理页允许编辑），仍按旧名改名，
-- 避免只认 code 时漏改。按旧名匹配已天然满足「改过就不再命中」的幂等性。
UPDATE menu
SET name = '资债权证记录'
WHERE name = '资债权证';
