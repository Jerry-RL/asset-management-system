-- ============================================================================
-- V58 「资产处置记录」菜单改挂到「资债权证记录」目录
--
-- 需求调整：该页从「资产运营」移到「资债权证记录」下。它本身是一份**记录 / 台账**
-- （一行 = 一个被处置的资产），与权证、抵押、调拨、权属流转同属「记录」性质，
-- 而不是「发起一次操作」的入口 —— 后者才是「资产运营」的语义。
--
-- 三件事一起做，缺一不可：
--   1. `menu.parent_id` 改指 `deed`（挂载位置）；
--   2. `menu.code` 随之改名 —— 仓内约定「菜单 code = 目录 code + '.' + 页面名」
--      （见 V45 §2.0 的口径说明）。只改 parent_id 不改 code，会让权限码停留在
--      `operation.*` 而菜单显示在「资债权证记录」下，权限矩阵与实际归属长期背离；
--   3. `role_permission.menu_code` 同步 —— 它是**反范式冗余列**。不同步的后果是
--      「按 menu_id 查权限正常、按 menu_code 查为空」，两种口径给出不同结果
--      （V54 / V55 / V57 的 view 回填语句都是按 menu_code 写的，后续新迁移也会照此写）。
--
-- 为什么是**新迁移**而不是回头改 V57：V57 已在环境上执行过，Flyway 会按 checksum 校验
-- 已应用的迁移，改它会让 `flyway.validate()` 失败、应用启动即失败
-- （`MigrationChainPostgresTest` 已把这一点钉住）。
--
-- 幂等：两条 UPDATE 都以 `code = 'operation.disposalRecord'` 为条件，重跑时该行已不存在，
-- 双双成为空操作；`menu.code` 上的唯一约束也保证不会撞码。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 改挂目录 + 改名 + 重排序号
--
-- 用 `UPDATE ... FROM menu d` 而不是子查询：`deed` 目录不存在时本语句**更新 0 行**，
-- 而标量子查询会写入 NULL 的 parent_id —— 那会让菜单变成一级目录（类型仍是 menu 却没有上级），
-- 侧边栏生成逻辑会直接跳过它，表现为「菜单凭空消失」且没有任何报错。
--
-- sort 47：`deed` 下已占用 10 / 20 / 30 / 40 / 45 / 46，47 落在「资产调拨记录」(46) 之后。
-- ---------------------------------------------------------------------------
UPDATE menu m
   SET code = 'deed.disposalRecord',
       parent_id = d.id,
       sort = 47
  FROM menu d
 WHERE m.code = 'operation.disposalRecord'
   AND d.code = 'deed';

-- ---------------------------------------------------------------------------
-- 2. 权限行同步改名
--
-- 只改 `menu_code`（反范式冗余列），**不动** `menu_id`：菜单行本身没有换，换的是它的编码。
-- 因此 `uk_role_menu_action (role_id, menu_id, action)` 不会受影响，不存在撞唯一约束的风险。
-- ---------------------------------------------------------------------------
UPDATE role_permission
   SET menu_code = 'deed.disposalRecord'
 WHERE menu_code = 'operation.disposalRecord';
